"""Tests for icon_map.json coverage — verifies extracted icon mappings exist.

Freezes which item categories have working icon mappings after extraction.
Each test class covers one category with real item IDs and exact DDS paths
from the actual icon_map.json generated by the extraction pipeline.

These tests use the on-disk icon_map.json and game_catalogue.json as fixtures.
They verify the EXTRACTION is correct, not the RESOLUTION (that's in test_icon_provider.py).
"""

import json
from pathlib import Path

import pytest


DATA_DIR = Path(__file__).resolve().parent.parent.parent / "src" / "nmstoolkit" / "data"
ICONS_DIR = DATA_DIR / "icons"


@pytest.fixture(scope="module")
def icon_map():
    """Load the real icon_map.json from disk."""
    path = ICONS_DIR / "icon_map.json"
    if not path.exists():
        pytest.skip("icon_map.json not available (run icon extraction first)")
    return json.loads(path.read_text())


@pytest.fixture(scope="module")
def catalogue():
    """Load the real game_catalogue.json from disk."""
    path = ICONS_DIR / "game_catalogue.json"
    if not path.exists():
        pytest.skip("game_catalogue.json not available (run icon extraction first)")
    return json.loads(path.read_text())


def _assert_in_map(icon_map, item_id, expected_dds):
    """Assert item_id maps to expected DDS path (checking both bare and ^-prefixed)."""
    dds = icon_map.get(item_id, "") or icon_map.get("^" + item_id, "")
    assert dds == expected_dds, f"{item_id}: expected {expected_dds}, got {dds!r}"



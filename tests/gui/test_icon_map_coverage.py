# ---------------------------------------------------------------------------
# KNOWN GAPS: Items NOT in icon_map (documented for Phase 2 fixes)
# ---------------------------------------------------------------------------

class TestIconMapKnownGaps:
    """Document items known to be missing from icon_map.

    These tests verify the gaps EXIST (are not accidentally fixed).
    When a gap is fixed in Phase 2, the corresponding test should be
    updated to assert the new mapping.
    """

    def test_proc_items_not_in_map(self, icon_map):
        """PROC_* procedural items are NOT in icon_map (known gap)."""
        proc_ids = [
            "PROC_BIO", "PROC_FOSS", "PROC_PLNT", "PROC_FARM",
            "PROC_SEA", "PROC_FEAR", "PROC_SALV", "PROC_BONE",
        ]
        for pid in proc_ids:
            assert pid not in icon_map, f"{pid} unexpectedly in icon_map"
            assert "^" + pid not in icon_map, f"^{pid} unexpectedly in icon_map"

# Category: Substances (minerals, gases, elements)
# User confirmed: icons correct on both Linux and Windows
# ---------------------------------------------------------------------------

class TestIconMapSubstances:
    """Substance items have correct DDS paths in icon_map."""

    def test_fuel1_carbon(self, icon_map):
        _assert_in_map(icon_map, "FUEL1", "TEXTURES/UI/FRONTEND/ICONS/U4SUBSTANCES/SUBSTANCE.FUEL.1.DDS")

    def test_oxygen(self, icon_map):
        _assert_in_map(icon_map, "OXYGEN", "TEXTURES/UI/FRONTEND/ICONS/U4SUBSTANCES/SUBSTANCE.AIR.1.DDS")

    def test_launchsub_dihydrogen(self, icon_map):
        _assert_in_map(icon_map, "LAUNCHSUB", "TEXTURES/UI/FRONTEND/ICONS/U4SUBSTANCES/SUBSTANCE.LAUNCHSUB.1.DDS")

    def test_land1_ferrite(self, icon_map):
        _assert_in_map(icon_map, "LAND1", "TEXTURES/UI/FRONTEND/ICONS/U4SUBSTANCES/SUBSTANCE.LAND.1.DDS")

    def test_catalyst1_sodium(self, icon_map):
        _assert_in_map(icon_map, "CATALYST1", "TEXTURES/UI/FRONTEND/ICONS/U4SUBSTANCES/SUBSTANCE.CATALYST.1.DDS")

    def test_substance_coverage(self, icon_map, catalogue):
        """At least 90 of ~107 substances should be in icon_map."""
        subs = catalogue["substances"]
